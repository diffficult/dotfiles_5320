local gaps_out = 5
local gaps_in = 2

local function set_gap(name, value)
  return function()
    if name == "gaps_out" then
      gaps_out = math.max(0, value(gaps_out))
      hl.dispatch(function()
        hl.config({ general = { gaps_out = gaps_out } })
      end)
    else
      gaps_in = math.max(0, value(gaps_in))
      hl.dispatch(function()
        hl.config({ general = { gaps_in = gaps_in } })
      end)
    end
  end
end

b.submap("gaps_outer", function()
  b.bind("8", set_gap("gaps_out", function(value) return value + 5 end), nil, { repeatable = true })
  b.bind("9", set_gap("gaps_out", function(value) return value - 5 end), nil, { repeatable = true })
  b.bind("0", set_gap("gaps_out", function() return 0 end), nil, {})
  b.bind("6", set_gap("gaps_out", function(value) return value + 5 end), nil, { repeatable = true })
  b.bind("7", set_gap("gaps_out", function(value) return value - 5 end), nil, { repeatable = true })
  b.bind("5", set_gap("gaps_out", function() return 0 end), nil, {})
  b.bind("Return", "submap", "reset", {})
  b.bind("Escape", "submap", "reset", {})
end)

